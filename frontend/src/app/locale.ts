export function localizeText(value: string): string {
  if (activeLocale === "zh" || !value) return value;
  if (EN[value]) return EN[value];
  const normalized = value.trim();
  if (exactShort.has(normalized)) {
    const start = value.length - value.trimStart().length;
    const end = value.length - value.trimEnd().length;
    return `${value.slice(0, start)}${EN[normalized]}${end ? value.slice(-end) : ""}`;
  }
  const templated = translateTemplate(value);
  if (templated !== undefined) return templated;
  let result = value;
  // Long, known UI phrases may be interpolated only after complete-template
  // handling. API-origin nodes use dataText() and never enter this path.
  for (const zh of knownPhrases) {
    if (result.includes(zh)) result = result.replaceAll(zh, EN[zh]!);
  }
  return result;
}

function localizeNode(node: Node): void {
  if (activeLocale === "en") {
    const record = originals.get(node) ?? { attributes: new Map<string, string>() };
    if (node.nodeType === Node.TEXT_NODE && record.text === undefined) record.text = node.textContent ?? "";
    if (node instanceof HTMLElement) for (const attr of ["aria-label", "title", "placeholder"]) {
      const value = node.getAttribute(attr);
      if (value && !record.attributes.has(attr)) record.attributes.set(attr, value);
    }
    originals.set(node, record);
  }
  if (activeLocale === "zh") {
    const original = originals.get(node);
    if (original?.text !== undefined && node.textContent !== original.text) node.textContent = original.text;
    if (node instanceof HTMLElement) for (const [attr, value] of original?.attributes ?? []) node.setAttribute(attr, value);
  }
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement;
    if (parent && !SKIP_PARENTS.has(parent.tagName.toLowerCase()) && !UNSAFE_TEXT.test(node.textContent?.trim() ?? "")) {
      let original = node.textContent ?? "";
      if (activeLocale === "en") original = originals.get(node)?.text ?? original;
      const translated = originals.get(node)?.raw ? original : localizeText(original);
      if (translated !== original) node.textContent = translated;
    }
    return;
  }
  if (!(node instanceof HTMLElement)) return;
  for (const attr of ["aria-label", "title", "placeholder"]) {
    let value = node.getAttribute(attr);
    if (value && activeLocale === "en") {
      const record = originals.get(node) ?? { attributes: new Map<string, string>() };
      if (!record.attributes.has(attr)) record.attributes.set(attr, value);
      else value = record.attributes.get(attr)!;
      originals.set(node, record);
      const translated = localizeText(value);
      if (translated !== value) node.setAttribute(attr, translated);
    }
  }
  for (const child of node.childNodes) localizeNode(child);
}

function localizePlaceholders(): void {
  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[placeholder]").forEach((node) => {
    if (activeLocale === "en") {
      const record = originals.get(node) ?? { attributes: new Map<string, string>() };
      if (!record.attributes.has("placeholder")) record.attributes.set("placeholder", node.placeholder);
      originals.set(node, record);
    }
    const original = originals.get(node)?.attributes.get("placeholder") ?? node.placeholder;
    node.placeholder = localizeText(original);
  });
}

function localizeDocument(): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = activeLocale === "en" ? "en" : "zh-CN";
  observer?.disconnect();
  localizeNode(document.body);
  localizePlaceholders();
  if (activeLocale === "en" && typeof MutationObserver !== "undefined") {
    observer = new MutationObserver((records) => {
      observer?.disconnect();
      localizePlaceholders();
      for (const record of records) {
        for (const node of record.addedNodes) localizeNode(node);
        if (record.type === "attributes") localizeNode(record.target);
        if (record.type === "characterData") localizeNode(record.target);
      }
      if (activeLocale === "en") observer?.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "title", "placeholder"] });
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "title", "placeholder"] });
  }
}

export function translateLocale(locale: Locale): void {
  if (locale === activeLocale) return;
  activeLocale = locale;
  localizeDocument();
}

export function localizeTree(node: Node): void {
  if (activeLocale === "en") localizeNode(node);
}

export function dataText(value: string): Text {
  const node = document.createTextNode(value);
  (node as Text & { __wealthosRaw?: boolean }).__wealthosRaw = true;
  originals.set(node, { text: value, raw: true, attributes: new Map<string, string>() });
  return node;
}
